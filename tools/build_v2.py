#!/usr/bin/env python3
"""v2 data build: extends the base factual datasets with short own-words descriptions (tools/item_info.txt),
unlock methods, pool fixes, extra entries and character stats; and writes data/sprites.js from the sprite manifest.
Facts (names, ids, numbers, unlock conditions) come from the Binding of Isaac wikis (CC BY-SA 3.0); prose is original."""
import json, os, re
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
items = json.load(open(os.path.join(here, 'items_base.json')))
chars = json.load(open(os.path.join(here, 'chars_base.json')))
man = json.load(open(os.path.join(here, 'sprites_manifest.json')))
FANDOM = 'https://bindingofisaacrebirth.fandom.com/wiki/'

# ---- items: fixes + new entries
POOL_FIX = {'c158': ['treasure'], 'c132': ['treasure', 'boss', 'devil'], 'c181': ['special'], 'c552': ['special'], 'c715': ['special']}
for it in items:
    if it['k'] in POOL_FIX: it['pools'] = POOL_FIX[it['k']]
have = {i['k'] for i in items}
NEW = [
 {"k":"c50","name":"Steven","n":50,"type":"passive","q":3,"dlc":0,"rc":None,"pools":["treasure","goldchest"]},
 {"k":"c120","name":"Odd Mushroom (Thin)","n":120,"type":"passive","q":2,"dlc":0,"rc":None,"pools":["treasure","boss","secret"]},
 {"k":"c121","name":"Odd Mushroom (Large)","n":121,"type":"passive","q":2,"dlc":0,"rc":None,"pools":["treasure","boss","secret"]},
 {"k":"c624","name":"Booster Pack","n":624,"type":"passive","q":1,"dlc":3,"rc":None,"pools":["boss","shop","crane"]},
]
for n in NEW:
    if n['k'] not in have: items.append(n)
items.sort(key=lambda i: (i['type'] == 'trinket', i['n']))
info = {}
for l in open(os.path.join(here, 'item_info.txt'), encoding='utf8').read().splitlines():
    if not l.strip(): continue
    k, d, u = (l.split('|') + ['', ''])[:3]; info[k] = (d.strip(), u.strip())
miss = [i['k'] for i in items if i['k'] not in info]
assert not miss, miss
for it in items:
    d, u = info[it['k']]; it['d'] = d
    if u: it['u'] = u
    s = man.get(it['k'])
    it['sp'] = 1 if s and s.get('file') else 0
hdr = "/* TBOIQ item dataset v2: factual attributes (Repentance baseline) + short original descriptions. Generated by tools/build_v2.py.\n   Facts from the Binding of Isaac wikis (CC BY-SA 3.0); see CREDITS.md. */\nwindow.TBOIQ_DATA = window.TBOIQ_DATA || {};\nwindow.TBOIQ_DATA.items = [\n"
open(os.path.join(root, 'data', 'items.js'), 'w', encoding='utf8').write(hdr + ',\n'.join(json.dumps(i, ensure_ascii=False, separators=(',', ':')) for i in items) + '\n];\n')

# ---- characters
st = json.load(open(os.path.join(here, 'raw_charstats.json')))
S = {  # k: (dmg_mult, tears_mod, shot, range, speed, luck)  overrides/fallbacks (base damage 3.5)
 'p4': (1.05, 0, 1, 6.5, 1.1, 0), 'p5': (0.75, 0, 1, 6.5, 1.23, 0), 'p7': (1.5, 0.5, 1, 4.5, 1.25, 0),
 'p9': None, 'p30': None, 'p16': (1.5, 0, 1, 6.5, 1.0, 0), 'p19': (1.0, 0.277, 1.15, 5.0, 1.0, 1),
 'p26': (1.2, -0.5, 1, 6.5, 1.0, 0), 'p28': (1.5, 0, 1, 6.5, 1.0, 0), 'p35': (1.5, 0, 1, 6.5, 1.0, 0),
}
START = {
 'p0': (['The D6'], 'bomb'), 'p1': (['Yum Heart'], 'pill'), 'p2': (['Lucky Foot'], 'key'), 'p3': (['The Book of Belial'], 'coin'),
 'p4': (['The Poop'], ''), 'p5': (['Razor Blade', 'Dead Bird'], ''), 'p6': (['Bloody Lust'], ''), 'p7': (['Brimstone'], 'card'),
 'p8': (['Anemic'], 'pill'), 'p9': (['Random active', 'Random passive'], 'random'), 'p10': (['Eternal D6', 'Holy Mantle'], 'coin'),
 'p13': (['Incubus', 'Cambion Conception', 'Box of Friends'], ''), 'p14': (['Wooden Nickel'], 'bomb'), 'p15': (['Void'], ''),
 'p16': (['Bone club'], ''), 'p18': (['Book of Virtues'], 'charge'), 'p19': ([], ''),
 'p21': ([], 'bomb'), 'p22': (['Yum Heart'], ''), 'p23': (['Bag of Crafting'], 'key'), 'p24': (['Dark Arts'], 'coin'),
 'p25': (['Hold'], 'bomb'), 'p26': (['Sumptorium'], ''), 'p27': ([], ''), 'p28': ([], 'card'), 'p29': (['Flip'], ''),
 'p30': (['Random active', 'Random passive'], 'random'), 'p31': ([], 'coin'), 'p32': ([], ''), 'p33': ([], 'bomb'),
 'p34': (['Abyss'], ''), 'p35': ([], ''), 'p36': (['Lemegeton'], 'charge'), 'p37': (['Anima Sola'], ''),
}
UNLOCK = {
 'p0': 'Unlocked from the start', 'p1': 'Hold 7+ red heart containers at once', 'p2': 'Hold 55 coins at once', 'p3': 'Defeat Satan',
 'p4': "Beat Mom's Heart ten times", 'p5': "Skip hearts for two floors in a row", 'p6': 'Clear two floors in a row without damage',
 'p7': 'Make three Devil deals in one run', 'p8': 'Hold 4+ soul hearts at once', 'p9': 'Complete Chapter 4',
 'p10': 'Die in a Sacrifice Room holding the Missing Poster', 'p13': 'Beat Ultra Greed as Azazel', 'p14': 'Donate 1000 coins to the Greed machine',
 'p15': 'Defeat Mega Satan', 'p16': 'Secret bone-hunt quest', 'p18': "Beat Mom's Heart/It Lives! on Hard as Lazarus without dying",
 'p19': 'Defeat Mother',
}
TAINT_UNLOCK = 'Open the Home closet with a Red Key as the base character'
base = {c['name']: c for c in chars if not c['tainted']}
TAINT_BASE = {'Tainted Isaac':'Isaac','Tainted Magdalene':'Magdalene','Tainted Cain':'Cain','Tainted Judas':'Judas','Tainted ???':'???','Tainted Eve':'Eve','Tainted Samson':'Samson','Tainted Azazel':'Azazel','Tainted Lazarus':'Lazarus','Tainted Eden':'Eden','Tainted Lost':'The Lost','Tainted Lilith':'Lilith','Tainted Keeper':'Keeper','Tainted Apollyon':'Apollyon','Tainted Forgotten':'The Forgotten','Tainted Bethany':'Bethany','Tainted Jacob':'Jacob & Esau'}
byname = {c['name']: c for c in chars}
for c in chars:
    k = c['k']; d = st.get(k) or {}
    s = S.get(k, 'parse')
    if s == 'parse':
        try: s = (float(d['dmult'] or 1), float(re.sub(r'[^0-9.+-]', '', d['tears']) or 0), float(d['shot']), float(d['range']), float(d['speed']), float(d['luck']))
        except Exception: s = None
    if s: c['stats'] = {'dmg': round(3.5 * s[0], 2), 'tears': s[1], 'shot': s[2], 'range': s[3], 'speed': s[4], 'luck': s[5]}
    names, pocket = START.get(k, ([], ''))
    c['start'] = names; c['pocketText'] = pocket
    c['u'] = UNLOCK.get(k) if not c['tainted'] else TAINT_UNLOCK
    if c['tainted']:
        c['twin'] = byname[TAINT_BASE[c['name']]]['k']
    else:
        t = [x for x in chars if x['tainted'] and TAINT_BASE[x['name']] == c['name']]
        if t: c['twin'] = t[0]['k']
    m = man.get(k, {})
    c['sp'] = (1 if m.get('icon') else 0) | (2 if m.get('portrait') else 0)
hdr = "/* TBOIQ character dataset v2: factual attributes (Repentance baseline). Generated by tools/build_v2.py.\n   stats.tears is the wiki's tear-rate modifier relative to Isaac. Facts from the Binding of Isaac wikis (CC BY-SA 3.0). */\nwindow.TBOIQ_DATA = window.TBOIQ_DATA || {};\nwindow.TBOIQ_DATA.characters = [\n"
open(os.path.join(root, 'data', 'characters.js'), 'w', encoding='utf8').write(hdr + ',\n'.join(json.dumps(c, ensure_ascii=False, separators=(',', ':')) for c in chars) + '\n];\n')

# ---- sprites manifest for the site
sp = {}
for k, m in man.items():
    if m.get('file'): sp[k] = [m['file'].replace('assets/sprites/', ''), m['page'].replace(FANDOM, '')]
    else:
        e = []
        if m.get('icon'): e.append(m['icon']['file'].replace('assets/sprites/', ''))
        if m.get('portrait'): e.append(m['portrait']['file'].replace('assets/sprites/', ''))
        if e: sp[k] = e + [m['page'].replace(FANDOM, '')]
open(os.path.join(root, 'data', 'sprites.js'), 'w', encoding='utf8').write("/* Sprite file index. Generated by tools/build_v2.py from tools/sprites_manifest.json.\n   items: [file, wikiPage]; chars: [icon, portrait, wikiPage]. Wiki page paths are relative to " + FANDOM + " */\nwindow.TBOIQ_DATA = window.TBOIQ_DATA || {};\nwindow.TBOIQ_DATA.spriteBase = 'assets/sprites/';\nwindow.TBOIQ_DATA.wikiBase = '" + FANDOM + "';\nwindow.TBOIQ_DATA.sprites = " + json.dumps(sp, separators=(',', ':'), ensure_ascii=False) + ";\n")
print(len(items), 'items;', sum(i['sp'] for i in items), 'with real sprite;', len(chars), 'chars')
